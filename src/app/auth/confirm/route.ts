import { type EmailOtpType } from "@supabase/supabase-js";
import { NextResponse, type NextRequest } from "next/server";
import { createClient } from "@/lib/supabase/server";

/** Destino dos links de e-mail (confirmação de conta e recuperação de senha). */
export async function GET(request: NextRequest) {
  const { searchParams, origin } = request.nextUrl;
  const tokenHash = searchParams.get("token_hash");
  const type = searchParams.get("type") as EmailOtpType | null;
  const code = searchParams.get("code");
  const nextParam = searchParams.get("next") ?? "/cliente";
  const next = nextParam.startsWith("/") && !nextParam.startsWith("//") ? nextParam : "/cliente";

  const supabase = await createClient();
  const { error } = tokenHash && type
    ? await supabase.auth.verifyOtp({ type, token_hash: tokenHash })
    : code
      ? await supabase.auth.exchangeCodeForSession(code)
      : { error: new Error("missing token") };

  if (error) {
    return NextResponse.redirect(`${origin}/entrar?erro=${encodeURIComponent("Link inválido ou expirado.")}`);
  }
  return NextResponse.redirect(`${origin}${next}`);
}
